# 1. Generic closed testing with weighted Bonferroni / weighted Simes tests
# --------------------------------------------------------------------------


def subsets(m: int):
    """All non-empty index subsets of {0, ..., m-1} as frozensets."""
    for r in range(1, m + 1):
        for c in itertools.combinations(range(m), r):
            yield frozenset(c)


def bonferroni_p(H, p, v):
    """Weighted Bonferroni p-value min_i p_i / v_i(H); v_i = 0 contributes 1."""
    vals = [p[i] / v[i] if v[i] > 0 else F(1) for i in H]
    return min(min(vals), F(1))


def simes_p(H, p, v, normalise=False):
    """Weighted Simes p-value min_l p_(l) / sum_{i<=l} v_(i) (Dmitrienko p. 2393).

    With normalise=True the weights are first rescaled to sum to one over H
    (the Benjamini-Hochberg 1997 form); the printed formula does not rescale.
    """
    order = sorted(H, key=lambda i: p[i])
    total = sum(v[i] for i in H)
    best = F(1)
    cum = F(0)
    for i in order:
        cum += v[i] / total if (normalise and total > 0) else v[i]
        if cum > 0:
            best = min(best, p[i] / cum)
    return best


def simes_p_normalised(H, p, v):
    return simes_p(H, p, v, normalise=True)


def singleton_full_level(weight_fn):
    """Table II convention (printed p. 2394): a singleton gatekeeper intersection uses p_i itself."""

    def fn(H):
        v = weight_fn(H)
        if len(H) == 1:
            (i,) = tuple(H)
            v = [F(0)] * len(v)
            v[i] = F(1)
        return v

    return fn


def closed_adjusted(m, p, weight_fn, local=bonferroni_p):
    """Adjusted p-values max over intersections containing H_i (Dmitrienko p. 2389)."""
    adj = [F(0)] * m
    for H in subsets(m):
        v = weight_fn(H)
        assert all(v[i] == 0 for i in range(m) if i not in H)
        assert sum(v) <= 1
        pH = local(H, p, v)
        for i in H:
            adj[i] = max(adj[i], pH)
    return adj


