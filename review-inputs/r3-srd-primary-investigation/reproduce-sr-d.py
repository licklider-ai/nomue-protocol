def wiens_fallback(alpha_prime, p):
    """Section 2.3 (printed p. 213): sequential rule with accumulation."""
    rejected = []
    prev_level = F(0)
    prev_rejected = False
    for i, (a, pi) in enumerate(zip(alpha_prime, p)):
        level = a + prev_level if prev_rejected else a
        if level > 0 and pi <= level:
            rejected.append(i)
            prev_rejected = True
        else:
            prev_rejected = False
        prev_level = level
    return frozenset(rejected)


