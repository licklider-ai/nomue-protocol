def remove_vertex(alpha, G, I, j):
    """One application of (A3)/(A4) = Step 3 of Algorithm 1 (printed pp. 591, 602-603)."""
    I2 = I - {j}
    a2 = {l: alpha[l] + alpha[j] * G[j][l] for l in I2}
    G2 = {l: {} for l in I2}
    for l in I2:
        for kk in I2:
            if l == kk:
                G2[l][kk] = F(0)
            else:
                den = 1 - G[l][j] * G[j][l]
                G2[l][kk] = (G[l][kk] + G[l][j] * G[j][kk]) / den if den != 0 else F(0)
    return a2, G2


def graph_weights(alpha, G, m, I):
    """Local levels for intersection I by removing vertices outside I (Remark (v))."""
    a = dict(alpha)
    g = {l: dict(G[l]) for l in G}
    cur = frozenset(range(m))
    for j in sorted(set(range(m)) - set(I)):
        a, g = remove_vertex(a, g, cur, j)
        cur = cur - {j}
    return a


def graph_algorithm1(alpha, G, p, m):
    """Algorithm 1 (printed p. 591): sequentially rejective shortcut."""
    I = frozenset(range(m))
    a = dict(alpha)
    g = {l: dict(G[l]) for l in G}
    rejected = []
    while I:
        cand = [i for i in I if a[i] > 0 and p[i] <= a[i]]
        if not cand:
            break
        j = min(I, key=lambda i: (p[i] / a[i]) if a[i] > 0 else F(10**9))
        if not (a[j] > 0 and p[j] <= a[j]):
            break
        rejected.append(j)
        a, g = remove_vertex(a, g, I, j)
        I = I - {j}
    return frozenset(rejected)


def graph_algorithm2(alpha, G, p, m, alpha_total):
    """Algorithm 2 (printed p. 595): adjusted p-values."""
    I = frozenset(range(m))
    w = {i: alpha[i] / alpha_total for i in range(m)}
    g = {l: dict(G[l]) for l in G}
    pmax = F(0)
    adj = {}
    while I:
        j = min(I, key=lambda i: (p[i] / w[i]) if w[i] > 0 else F(10**9))
        pj = p[j] / w[j] if w[j] > 0 else F(1)
        adj[j] = min(max(pj, pmax), F(1))
        pmax = adj[j]
        w, g = remove_vertex(w, g, I, j)
        I = I - {j}
    return adj


def closed_rejections_from_graph(alpha, G, m, p, alpha_total):
    """Full closure with weighted Bonferroni tests whose weights come from the graph."""
    rej = set()
    for i in range(m):
        ok = True
        for H in subsets(m):
            if i not in H:
                continue
            a = graph_weights(alpha, G, m, H)
            if not any(a[l] > 0 and p[l] <= a[l] for l in H):
                ok = False
                break
        if ok:
            rej.add(i)
    return frozenset(rej)


def chain_graph(m, eps=F(0)):
    G = {i: {j: F(0) for j in range(m)} for i in range(m)}
    for i in range(m - 1):
        G[i][i + 1] = F(1)
    return G


