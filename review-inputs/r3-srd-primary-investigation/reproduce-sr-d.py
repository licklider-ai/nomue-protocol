def dow_parallel_weights(k, m, w):
    """Algorithm 1 (printed p. 2390): parallel Bonferroni gatekeeping weights."""
    gate = set(range(k))

    def fn(H):
        v = [F(0)] * m
        gates_in = [i for i in H if i in gate]
        secs_in = [i for i in H if i not in gate]
        if len(gates_in) == k:  # Case 1
            for i in gates_in:
                v[i] = w[i]
        elif gates_in:  # Case 2
            rem = 1 - sum(w[i] for i in gates_in)
            den = sum(w[i] for i in secs_in)
            for i in gates_in:
                v[i] = w[i]
            for i in secs_in:
                v[i] = w[i] * rem / den
        else:  # Case 3
            den = sum(w[i] for i in secs_in)
            for i in secs_in:
                v[i] = w[i] / den
        return v

    return fn


def dow_serial_weights(k, m, w):
    """Algorithm 2 (printed p. 2391): serial Bonferroni gatekeeping weights."""
    gate = set(range(k))

    def fn(H):
        v = [F(0)] * m
        gates_in = [i for i in H if i in gate]
        secs_in = [i for i in H if i not in gate]
        if gates_in:  # Case 1
            den = sum(w[i] for i in gates_in)
            for i in gates_in:
                v[i] = w[i] / den
        else:  # Case 2
            den = sum(w[i] for i in secs_in)
            for i in secs_in:
                v[i] = w[i] / den
        return v

    return fn


