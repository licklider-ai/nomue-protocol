def pava(x, n=None):
    """Isotonic (non-decreasing) weighted least squares by pool-adjacent-violators."""
    n = n or [1] * len(x)
    blocks = [[F(v), F(w), 1] for v, w in zip(x, n)]  # value, weight, count
    i = 0
    while i < len(blocks) - 1:
        if blocks[i][0] > blocks[i + 1][0]:
            v = (blocks[i][0] * blocks[i][1] + blocks[i + 1][0] * blocks[i + 1][1]) / (
                blocks[i][1] + blocks[i + 1][1]
            )
            blocks[i] = [v, blocks[i][1] + blocks[i + 1][1], blocks[i][2] + blocks[i + 1][2]]
            del blocks[i + 1]
            i = max(i - 1, 0)
        else:
            i += 1
    out = []
    for v, _w, c in blocks:
        out.extend([v] * c)
    return out


def d2_statistic(xbar, partition):
    """D_g^2 of printed p. 657 with n_i = 1 and sigma^2 = 1."""
    total = F(0)
    for block in partition:
        vals = [F(xbar[i - 1]) for i in block]
        mean = sum(vals) / len(vals)
        fit = pava(vals)
        total += sum((f - mean) ** 2 for f in fit)
    return total


def stirling1_unsigned(n):
    """|s(n, m)| for m = 0..n."""
    row = [1]
    for i in range(n):
        new = [0] * (len(row) + 1)
        for m_, c in enumerate(row):
            new[m_] += i * c
            new[m_ + 1] += c
        row = new
    return row


def level_probabilities(lam):
    """p(m; lambda) for equal sample sizes: |s(lambda, m)| / lambda!."""
    s = stirling1_unsigned(lam)
    return {m_: F(s[m_], math.factorial(lam)) for m_ in range(1, lam + 1)}


def chi2_sf(df, x):
    """Upper tail of chi-square with integer df (closed forms; df = 0 gives 0)."""
    if df == 0:
        return 0.0
    if x <= 0:
        return 1.0
    if df % 2 == 0:
        n = df // 2
        term = 1.0
        total = 0.0
        for i in range(n):
            if i > 0:
                term *= (x / 2) / i
            total += term
        return math.exp(-x / 2) * total
    n = (df - 1) // 2
    total = math.erfc(math.sqrt(x / 2))
    coeff = math.sqrt(2 * x / math.pi) * math.exp(-x / 2)
    term = 1.0  # x^(i-1) / (1 * 3 * ... * (2i-1)) for i = 1, ..., n
    for i in range(1, n + 1):
        if i > 1:
            term *= x / (2 * i - 1)
        total += coeff * term
    return total


def dg2_sf(lams, t2):
    """pr(D_g^2 > t^2) from the equal-n formula on printed p. 658."""
    probs = [level_probabilities(lam) for lam in lams]
    total = 0.0
    for ms in itertools.product(*[range(1, lam + 1) for lam in lams]):
        prob = 1.0
        for pj, m_ in zip(probs, ms):
            prob *= float(pj[m_])
        df = sum(ms) - len(lams)
        total += prob * chi2_sf(df, t2)
    return total


def dg2_critical(lams, alpha):
    lo, hi = 0.0, 60.0
    for _ in range(200):
        mid = (lo + hi) / 2
        if dg2_sf(lams, mid) > alpha:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


def norm_quantile(q):
    lo, hi = -10.0, 10.0
    for _ in range(200):
        mid = (lo + hi) / 2
        if 0.5 * math.erfc(-mid / math.sqrt(2)) < q:
            lo = mid
        else:
            hi = mid
    return (lo + hi) / 2


