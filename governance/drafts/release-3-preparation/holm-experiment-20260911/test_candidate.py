"""Author-side experiments; explicit checks also run under python -O."""
from pathlib import Path
import hashlib, json
ROOT=Path(__file__).resolve().parent
for name, digest in json.loads((ROOT/'INPUTS.json').read_text())['sha256'].items():
    if hashlib.sha256((ROOT/name).read_bytes()).hexdigest()!=digest:
        raise ValueError('source hash mismatch: '+name)

from candidate import transform, check_evidence, U, project
from oracle import closed_testing, display
from fractions import Fraction as Q
from struct import pack
from copy import deepcopy
import random, time, resource, platform

counts={}
def check(name, yes):
    if not yes: raise RuntimeError(name)
    counts[name]=counts.get(name,0)+1

def reject(name, fn, reason):
    try: fn()
    except ValueError as e: check(name,type(e) is ValueError and str(e)==reason)
    else: raise RuntimeError('accepted: '+name)

def carrier(ps):
    return {'family':'family','revision':'revision','members':[{'hypothesis':str(i),'origin':'supplied','p':pack('>d',float(x))} for i,x in enumerate(ps)]}

rng=random.Random(20260911)
for m in range(1,9):
    for _ in range(40):
        c=carrier([Q(rng.randrange(257),256) for i in range(m)])
        out=transform(c)
        expected=closed_testing([x['p'] for x in c['members']])
        check('closed-testing agreement',[Q(a,U) for a in out['adjusted_lattice']]==expected)
        check('display agreement',out['display']==[display(x) for x in expected])
        check('self evidence',check_evidence(c,out))
        alpha=Q(rng.randrange(1,100),100)
        seq=[]
        for i in out['order']:
            if Q(out['input_lattice'][i],U)*(m-len(seq))>alpha: break
            seq.append(i)
        check('exact step-down',set(seq)=={i for i,q in enumerate(expected) if q<=alpha})

for ps,expected in [([Q(3,4),Q(1,2)],[Q(1),Q(1)]),([0,0,1],[0,0,1]),([Q(1,1<<1074)]*2,[Q(2,1<<1074)]*2)]:
    check('explicit boundary',[Q(a,U) for a in transform(carrier(ps))['adjusted_lattice']]==expected)
for a in [0,1,(1<<52)-1,1<<52,U-1,U]+[rng.randrange(U+1) for _ in range(2000)]:
    check('projection oracle',project(a)==display(Q(a,U)))
c=carrier([Q(1,4)+3*Q(1,1<<54)]*3);out=transform(c)
bad=deepcopy(out);bad['adjusted_lattice'][0]-=1<<1020
check('collision display equal',project(bad['adjusted_lattice'][0])==out['display'][0])
reject('collision rejected',lambda:check_evidence(c,bad),'evidence mismatch')
for field,value in [('family','other'),('revision','other')]:
    bad=deepcopy(out);bad['carrier'][field]=value
    reject('identity substitution',lambda:check_evidence(c,bad),'evidence mismatch')
for field,value in [('hypothesis','other'),('origin','other')]:
    bad=deepcopy(out);bad['carrier']['members'][0][field]=value
    reject('member substitution',lambda:check_evidence(c,bad),'evidence mismatch')
bad=deepcopy(out);bad['order'][0]=True
reject('bool evidence',lambda:check_evidence(c,bad),'evidence mismatch')
# Runtime sort counters are diagnostics: changing them must not alter evidence acceptance,
# and evidence regenerated by a different sort implementation stays checkable.
diag=deepcopy(out);diag['comparisons']={'identity':0,'values':0}
check('diagnostics excluded from identity',check_evidence(c,diag))
reject('evidence shape',lambda:check_evidence(c,[out]),'evidence shape')
# Both midpoint parity directions from the design: ties-to-even rounds up when q is odd
# and down when q is even. Exhaustive exact ties across every binade and both parities.
up=transform(carrier([Q(1,4)+Q(1,1<<54)]*3))
check('upward midpoint',up['adjusted_lattice'][0]==int((Q(3,4)+Q(3,1<<54))*U) and up['display'][0]==pack('>d',0.75+2**-52))
for s in range(1,1023):
    for q in ((1<<52),(1<<52)+1,(1<<53)-2,(1<<53)-1):
        a=(q<<s)+(1<<(s-1))
        if a<=U: check('exact tie parity',project(a)==display(Q(a,U)))
# The comparison budget refuses with its stated reason instead of running unbounded.
from candidate import ordered
reject('comparison budget',lambda:ordered(range(20000),lambda i:-i),'comparison budget')
for _ in range(50):
    seq=[rng.randrange(1024) for _ in range(1024)]
    check('budget headroom',ordered(range(1024),lambda i:(seq[i],i))[1]<=10240)
for raw in [pack('>d',-0.0),pack('>d',float('nan')),pack('>d',float('inf')),pack('>d',1.01)]:
    bad=carrier([0]);bad['members'][0]['p']=raw
    reject('bad p',lambda:transform(bad),'p domain')
for ps in [[],[0]*1025]: reject('count',lambda:transform(carrier(ps)),'family count')
bad=carrier([0,0]);bad['members'][1]['hypothesis']='0'
reject('duplicate',lambda:transform(bad),'duplicate hypothesis')
c=carrier([0,0]);c['members'][0]['hypothesis']='A';c['members'][1]['hypothesis']='a'
check('case distinct',len(transform(c)['adjusted_lattice'])==2)
bad=carrier([0]);bad['family']='a b'
reject('label characters',lambda:transform(bad),'label characters')
bad=carrier([0]);bad['revision']='x'*65
reject('label length',lambda:transform(bad),'label length')
bad=carrier([0]);bad['members'][0]['p']=b'bad'
reject('byte length',lambda:transform(bad),'p bytes')
# Permute full members and preserve hypothesis-associated adjusted values.
c=carrier([Q(1,8),Q(1,8),Q(1,2),0,1]); original=transform(c)
c['members'].reverse(); permuted=transform(c)
check('permutation invariant',dict(zip([x['hypothesis'] for x in original['carrier']['members']],original['adjusted_lattice']))==dict(zip([x['hypothesis'] for x in c['members']],permuted['adjusted_lattice'])))
bad=deepcopy(permuted);bad['display'][0]=bytes(8)
reject('display substitution',lambda:check_evidence(c,bad),'evidence mismatch')
bad=deepcopy(permuted);bad['inverse'].reverse()
reject('permutation substitution',lambda:check_evidence(c,bad),'evidence mismatch')
for k in range(52,1075):
    for a in ((1<<k)-1,1<<k):
        check('binade projection',project(a)==display(Q(a,U)))
check('all ones',transform(carrier([1]*8))['adjusted_lattice']==[U]*8)
check('all zeros',transform(carrier([0]*8))['adjusted_lattice']==[0]*8)
bench=[]
for label,ps in [('reverse',[Q(i,1024) for i in range(1024,0,-1)]),('ties',[Q(1,2)]*1024),('extremes',[0,Q(1,1<<1074),Q(1,2),1]*256)]:
    c=carrier(ps)
    c['family']='f'*64;c['revision']='r'*64
    for i,x in enumerate(c['members']): x['hypothesis']=str(i).zfill(64);x['origin']='o'*64
    start=time.perf_counter();out=transform(c);check_evidence(c,out);elapsed=time.perf_counter()-start
    check('maximum admission',len(out['display'])==1024 and elapsed<10)
    bench.append({'case':label,'seconds_transform_and_check':elapsed,'comparisons':out['comparisons']})
result={'assertions':counts,'total':sum(counts.values()),'benchmarks':bench,'max_rss_kib':resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,'python':platform.python_version()}
(ROOT/'RESULTS.json').write_text(json.dumps(result,indent=2)+'\n')
print(json.dumps(result))
